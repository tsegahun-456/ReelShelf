CREATE TABLE local_media (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_path TEXT NOT NULL UNIQUE,
    file_name VARCHAR(600) NOT NULL,
    display_title VARCHAR(400) NOT NULL,
    media_kind VARCHAR(16) NOT NULL,
    series_title VARCHAR(300),
    season_number INTEGER,
    episode_number INTEGER,
    episode_title VARCHAR(300),
    subtitle_path TEXT,
    file_size BIGINT NOT NULL,
    modified_at TIMESTAMP WITH TIME ZONE NOT NULL,
    title_override VARCHAR(400),
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT local_media_kind_check CHECK (media_kind IN ('MOVIE', 'EPISODE'))
);
CREATE INDEX local_media_kind_title_idx ON local_media (media_kind, display_title);
CREATE INDEX local_media_episode_order_idx ON local_media (series_title, season_number, episode_number);
