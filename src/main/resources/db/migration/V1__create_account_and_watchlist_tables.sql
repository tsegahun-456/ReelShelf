CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE watchlist_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    media_type VARCHAR(16) NOT NULL,
    title VARCHAR(300) NOT NULL,
    poster_path VARCHAR(300),
    backdrop_path VARCHAR(300),
    release_date VARCHAR(32),
    vote_average NUMERIC(4, 2),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT watchlist_entry_media_type_check CHECK (media_type IN ('MOVIE', 'TV')),
    CONSTRAINT watchlist_entry_unique_media UNIQUE (user_id, tmdb_id, media_type)
);

CREATE INDEX watchlist_entry_user_created_idx
    ON watchlist_entry (user_id, created_at DESC);
