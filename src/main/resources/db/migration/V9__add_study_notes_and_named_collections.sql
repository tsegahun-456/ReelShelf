CREATE TABLE media_study_note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL REFERENCES local_media(id) ON DELETE CASCADE,
    at_seconds BIGINT NOT NULL,
    note_text VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT media_study_note_at_check CHECK (at_seconds >= 0)
);
CREATE INDEX media_study_note_media_time_idx ON media_study_note (media_id, at_seconds, id);

CREATE TABLE user_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_collection_user_name_unique UNIQUE (user_id, name)
);

CREATE TABLE user_collection_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES user_collection(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    media_type VARCHAR(16) NOT NULL,
    title VARCHAR(300) NOT NULL,
    poster_path VARCHAR(300),
    release_date VARCHAR(32),
    vote_average NUMERIC(4, 2),
    genre_names VARCHAR(1000),
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_collection_item_media_type_check CHECK (media_type IN ('MOVIE', 'TV')),
    CONSTRAINT user_collection_item_title_unique UNIQUE (collection_id, tmdb_id, media_type)
);
CREATE INDEX user_collection_item_collection_added_idx ON user_collection_item (collection_id, added_at DESC);
