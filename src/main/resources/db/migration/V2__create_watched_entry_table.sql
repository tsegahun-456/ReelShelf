CREATE TABLE watched_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    media_type VARCHAR(16) NOT NULL,
    title VARCHAR(300) NOT NULL,
    poster_path VARCHAR(300),
    backdrop_path VARCHAR(300),
    release_date VARCHAR(32),
    vote_average NUMERIC(4, 2),
    user_rating INTEGER,
    watched_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT watched_entry_media_type_check CHECK (media_type IN ('MOVIE', 'TV')),
    CONSTRAINT watched_entry_user_rating_check CHECK (user_rating IS NULL OR user_rating BETWEEN 1 AND 5),
    CONSTRAINT watched_entry_unique_media UNIQUE (user_id, tmdb_id, media_type)
);

CREATE INDEX watched_entry_user_date_idx
    ON watched_entry (user_id, watched_at DESC);
