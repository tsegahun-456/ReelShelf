CREATE TABLE IF NOT EXISTS local_media_poster_cache (
    tmdb_media_type VARCHAR(16) NOT NULL,
    tmdb_id BIGINT NOT NULL,
    poster_path VARCHAR(300) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    poster_data BYTEA NOT NULL,
    cached_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (tmdb_media_type, tmdb_id)
);

-- Persistent sign-in ("Keep me signed in"); the entity tables are also created
-- by JPA (ddl-auto=update) but are listed here to keep the portable schema explicit.
CREATE TABLE IF NOT EXISTS persistent_logins (
    username VARCHAR(320) NOT NULL,
    series VARCHAR(64) PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    last_used TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS firebase_credential (
    email VARCHAR(254) PRIMARY KEY,
    firebase_uid VARCHAR(128) NOT NULL,
    display_name VARCHAR(80) NOT NULL DEFAULT '',
    refresh_token_encrypted VARCHAR(1024) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Folders the local media scanner walks (Settings page).
CREATE TABLE IF NOT EXISTS media_scan_root (
    path VARCHAR(1000) PRIMARY KEY,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 0.3.0 local notes, review metadata, manual series grouping and named lists.
ALTER TABLE local_media ADD COLUMN IF NOT EXISTS tmdb_match_reviewed BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE local_media ADD COLUMN IF NOT EXISTS parser_version INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS media_study_note (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL REFERENCES local_media(id) ON DELETE CASCADE,
    at_seconds BIGINT NOT NULL CHECK (at_seconds >= 0),
    note_text VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS media_study_note_media_time_idx ON media_study_note (media_id, at_seconds, id);
CREATE TABLE IF NOT EXISTS user_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_collection_user_name_unique UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS user_collection_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_id BIGINT NOT NULL REFERENCES user_collection(id) ON DELETE CASCADE,
    tmdb_id BIGINT NOT NULL,
    media_type VARCHAR(16) NOT NULL CHECK (media_type IN ('MOVIE', 'TV')),
    title VARCHAR(300) NOT NULL,
    poster_path VARCHAR(300),
    release_date VARCHAR(32),
    vote_average NUMERIC(4,2),
    genre_names VARCHAR(1000),
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_collection_item_title_unique UNIQUE (collection_id, tmdb_id, media_type)
);
CREATE INDEX IF NOT EXISTS user_collection_item_collection_added_idx ON user_collection_item (collection_id, added_at DESC);
CREATE TABLE IF NOT EXISTS local_series_group_alias (
    alias_key VARCHAR(300) PRIMARY KEY,
    alias_title VARCHAR(300) NOT NULL,
    canonical_title VARCHAR(300) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
